# shellcheck shell=bash
# Core config, core extras, and the profile and manual installers.

SHELL_FILES=(.commonrc .aliases .functions)
ZSH_FILES=(.zshrc .p10k.zsh)
PROFILE_STATE_FILE="$DOTFILES_DIR/.active-profile"

ensure_ohmyzsh() {
    if [[ -d "$HOME/.oh-my-zsh" ]]; then
        return 0
    fi

    _info "Installing Oh My Zsh..."
    RUNZSH=no CHSH=no sh -c "$(curl -fsSL https://raw.githubusercontent.com/ohmyzsh/ohmyzsh/master/tools/install.sh)"
    _success "Oh My Zsh installed"
}

ensure_p10k() {
    local p10k_dir="${ZSH_CUSTOM:-$HOME/.oh-my-zsh/custom}/themes/powerlevel10k"
    if [[ -d "$p10k_dir" ]]; then
        return 0
    fi

    _info "Installing Powerlevel10k..."
    git clone --depth=1 https://github.com/romkatv/powerlevel10k.git "$p10k_dir"
    _success "Powerlevel10k installed"
}


install_shell_config() {
    mkdir -p "$BACKUP_DIR"

    for file in "${SHELL_FILES[@]}"; do
        if [[ -f "$DOTFILES_DIR/$file" ]]; then
            link_file "$DOTFILES_DIR/$file" "$HOME/$file"
        else
            _warn "File not found: $file"
        fi
    done

    local source_line='[[ -f "$HOME/.commonrc" ]] && source "$HOME/.commonrc"'

    # ~/.bashrc is system-owned (never a long-lived symlink). Recover broken
    # leftovers from a path migration (e.g. ~/dotfiles -> ~/.dotfiles) by
    # installing the repo reference as a real file, then ensure it sources
    # .commonrc.
    if [[ -L "$HOME/.bashrc" && ! -e "$HOME/.bashrc" ]]; then
        backup_item "$HOME/.bashrc"
        rm -f "$HOME/.bashrc"
        if [[ -f "$DOTFILES_DIR/.bashrc" ]]; then
            cp "$DOTFILES_DIR/.bashrc" "$HOME/.bashrc"
            _success "Restored ${_DIM}~/.bashrc${_RESET} from repo (was a broken symlink)"
        fi
    fi

    if [[ ! -f "$HOME/.bashrc" ]]; then
        if [[ -f "$DOTFILES_DIR/.bashrc" ]]; then
            cp "$DOTFILES_DIR/.bashrc" "$HOME/.bashrc"
            _success "Installed ${_DIM}~/.bashrc${_RESET} from repo"
        else
            _warn "No ~/.bashrc found — copy the reference from $DOTFILES_DIR/.bashrc"
        fi
    elif grep -qF '.commonrc' "$HOME/.bashrc" 2>/dev/null; then
        _info "~/.bashrc already sources .commonrc"
    else
        printf '\n# Dotfiles customizations\n%s\n' "$source_line" >> "$HOME/.bashrc"
        _success "Added commonrc source line to ${_DIM}~/.bashrc${_RESET}"
    fi
}

install_zsh_config() {
    ensure_ohmyzsh
    ensure_p10k

    local zsh_plugins=(zsh-autosuggestions zsh-you-should-use zsh-syntax-highlighting)
    for plugin in "${zsh_plugins[@]}"; do
        if ! brew list "$plugin" &>/dev/null; then
            _info "Installing $plugin..."
            brew install "$plugin"
            _success "$plugin installed"
        fi
    done

    for file in "${ZSH_FILES[@]}"; do
        if [[ -f "$DOTFILES_DIR/$file" ]]; then
            link_file "$DOTFILES_DIR/$file" "$HOME/$file"
        else
            _warn "File not found: $file"
        fi
    done
}

install_default_terminal() {
    if ! command -v omarchy &>/dev/null; then
        _warn "omarchy command not found — skipping default terminal setup"
        return 0
    fi

    local current=""
    current="$(omarchy default terminal 2>/dev/null || true)"
    if [[ "$current" == "alacritty" ]]; then
        _info "Default terminal already set to alacritty"
        return 0
    fi

    if omarchy default terminal alacritty; then
        _success "Set default terminal to alacritty"
    else
        _warn "Failed to set default terminal to alacritty"
    fi
}

install_ssh_config() {
    if [[ ! -d "$HOME/.ssh" ]]; then
        mkdir -p "$HOME/.ssh"
        chmod 700 "$HOME/.ssh"
    fi

    local agent_sock
    if [[ "$OSTYPE" == darwin* ]]; then
        agent_sock="~/Library/Group Containers/2BUA8C4S2C.com.1password/t/agent.sock"
    else
        agent_sock="~/.1password/agent.sock"
    fi

    local cfg="$HOME/.ssh/config" want
    # printf, not a heredoc in $(…): bash 3.2 misparses ")" inside one.
    want="$(printf '%s\n' \
        '# Machine-local SSH config (generated by dotfiles install.sh)' \
        '# Override IdentityAgent for this OS' \
        'Host *' \
        "  IdentityAgent \"$agent_sock\"" \
        '' \
        '# Shared config from dotfiles submodule' \
        "Include $DOTFILES_DIR/.ssh/config")"
    if [[ -f "$cfg" && ! -L "$cfg" && "$(<"$cfg")" == "$want" ]]; then
        chmod 600 "$cfg"
        _info "${_DIM}.ssh/config${_RESET} already generated"
    else
        backup_item "$cfg"
        rm -f "$cfg"
        printf '%s\n' "$want" > "$cfg"
        chmod 600 "$cfg"
        _success "Generated ${_DIM}.ssh/config${_RESET}"
    fi

    if [[ ! -f "$DOTFILES_DIR/.ssh/config" ]]; then
        _warn "SSH submodule not populated yet — Include will resolve after: ${_BOLD}git -C $DOTFILES_DIR submodule update --init .ssh${_RESET}"
    fi
}

install_git_config() {
    if [[ -f "$DOTFILES_DIR/.gitconfig.dotfiles" ]]; then
        link_file "$DOTFILES_DIR/.gitconfig.dotfiles" "$HOME/.gitconfig"
    else
        _warn ".gitconfig.dotfiles not found"
    fi

    local git_local="$HOME/.gitconfig.local"

    if [[ ! -t 0 ]]; then
        [[ -f "$git_local" ]] || _warn "No terminal to ask for Git name/email — write ${git_local} or rerun ./install.sh in a terminal"
        return 0
    fi

    if [[ -f "$git_local" ]]; then
        _info "Local Git config already exists at ${_DIM}$git_local${_RESET}"
        read -rp "Reconfigure Git settings? (y/N): " reconfigure
        if [[ ! "$reconfigure" =~ ^[Yy]$ ]]; then
            return
        fi
        backup_item "$git_local"
    fi

    read -rp "Enter your Git name: " git_name
    read -rp "Enter your Git email: " git_email

    echo
    read -rp "Enable Git commit signing? (y/N): " enable_signing

    if [[ "$enable_signing" =~ ^[Yy]$ ]]; then
        echo
        echo "Which SSH agent for signing?"
        echo "  1) ssh-keygen (default)"
        echo "  2) 1Password SSH Agent"
        read -rp "Choice (1 or 2): " agent_choice
        read -rp "Enter your Git public signing key: " signing_key

        local ssh_program="ssh-keygen"
        if [[ "$agent_choice" == "2" ]]; then
            if [[ "$OSTYPE" == darwin* ]]; then
                ssh_program="/Applications/1Password.app/Contents/MacOS/op-ssh-sign"
            else
                ssh_program="/opt/1Password/op-ssh-sign"
            fi
        fi

        cat > "$git_local" <<EOF
[user]
    name = $git_name
    email = $git_email
    signingkey = $signing_key

[gpg]
    format = ssh
[gpg "ssh"]
    program = $ssh_program
[commit]
    gpgsign = true
EOF
        _success "Git signing enabled"
    else
        cat > "$git_local" <<EOF
[user]
    name = $git_name
    email = $git_email
EOF
        _success "Git config created (signing disabled)"
    fi
}

ai_harness_label() {
    local name alias resume
    case "$1" in
        claude) name="Claude Code" ;;
        grok) name="Grok" ;;
        opencode) name="OpenCode" ;;
        *) return 1 ;;
    esac
    IFS=$'\t' read -r alias resume < <(ai_harness_cli "$1")
    printf '%s — %s, resume: %s\n' "$name" "$alias" "$resume"
}

# gum picker over the enabled harnesses, profile default first. Prints the
# chosen harness id; prompts go to stderr because callers capture stdout.
ai_pick_harness() {
    local prompt="$1" default h choice
    local -a order=()
    default="$(profile_ai_default)"
    if [[ -n "$default" ]] && ai_harness_enabled "$default"; then
        order+=("$default")
    fi
    while IFS= read -r h; do
        if [[ -n "$h" && "$h" != "$default" ]]; then
            order+=("$h")
        fi
    done < <(ai_enabled_harnesses)
    if ((${#order[@]} == 0)); then
        _warn "No AI harness is enabled on this machine" >&2
        return 1
    fi

    echo >&2
    _info "$prompt" >&2
    echo >&2
    choice="$(for h in "${order[@]}"; do ai_harness_label "$h"; done | gum choose --height=6)" || return 1
    for h in "${order[@]}"; do
        if [[ "$(ai_harness_label "$h")" == "$choice" ]]; then
            printf '%s\n' "$h"
            return 0
        fi
    done
    return 1
}

# Replace the AI_TOOL / AI_TOOL_RESUME block in ~/.localrc. Also drops the
# AI_TOOL_PIPE line older versions wrote.
write_ai_tool_localrc() {
    local ai_tool="$1" ai_resume="$2"
    local localrc="$HOME/.localrc"

    if [[ -f "$localrc" ]] && grep -qE '^export AI_TOOL(_RESUME|_PIPE)?=' "$localrc" 2>/dev/null; then
        backup_item "$localrc"
        local tmp
        tmp="$(mktemp)"
        grep -vE '^export AI_TOOL(_RESUME|_PIPE)?=' "$localrc" > "$tmp" || true
        # Drop the trailing "AI CLI tool" comment if we added one previously.
        # Avoid `sed -i` (GNU vs BSD/macOS differ); rewrite via temp file.
        if grep -q '^# AI CLI tool' "$tmp" 2>/dev/null; then
            local tmp2
            tmp2="$(mktemp)"
            grep -v '^# AI CLI tool' "$tmp" > "$tmp2" || true
            mv "$tmp2" "$tmp"
        fi
        mv "$tmp" "$localrc"
    fi

    {
        [[ -s "$localrc" ]] && echo ""
        echo "# AI CLI tool (tav, wtc, wta)"
        echo "export AI_TOOL=\"$ai_tool\""
        echo "export AI_TOOL_RESUME=\"$ai_resume\""
    } >> "$localrc"

    note_change "AI_TOOL=$ai_tool in ~/.localrc"
    _success "Set AI_TOOL=$ai_tool, AI_TOOL_RESUME=\"$ai_resume\" in ${_DIM}~/.localrc${_RESET}"
    _info "Reload current shell: ${_BOLD}source ~/.localrc${_RESET}  (or open a new shell)"
}

# `dot ai-tool [TOOL]`: pick the harness tav, wtc and wta launch. Only
# harnesses the profile allows are offered.
install_ai_tool() {
    local localrc="$HOME/.localrc"
    local interactive_arg="${1:-}"
    local tool_h ai_tool ai_resume

    if [[ -n "$interactive_arg" ]]; then
        if ! tool_h="$(ai_harness_normalize "$interactive_arg")"; then
            _error "Unknown AI tool: $interactive_arg (choose: cl, gra, oc)"
            return 1
        fi
        if ! ai_harness_allowed "$tool_h"; then
            _error "$tool_h is not in profiles/$(read_active_profile).yaml"
            return 1
        fi
    else
        if [[ -f "$localrc" ]] && grep -qE '^export AI_TOOL=' "$localrc" 2>/dev/null; then
            local current
            current="$(grep -E '^export AI_TOOL=' "$localrc" | head -1 | sed -E 's/^export AI_TOOL=//; s/^"(.*)"$/\1/')"
            _info "AI tool already set in ${_DIM}~/.localrc${_RESET}: ${_BOLD}$current${_RESET}"
            read -rp "Reconfigure? (y/N): " reconfigure
            if [[ ! "$reconfigure" =~ ^[Yy]$ ]]; then
                return
            fi
        fi

        if ! command -v gum &>/dev/null; then
            _warn "gum not available — pass the tool name directly: dot ai-tool {cl|gra|oc}"
            return 0
        fi

        if ! tool_h="$(ai_pick_harness "Select your preferred AI CLI (used by tav, wtc, wta):")"; then
            _info "No selection — leaving AI_TOOL unchanged"
            return 0
        fi
    fi

    IFS=$'\t' read -r ai_tool ai_resume <<<"$(ai_harness_cli "$tool_h")"
    write_ai_tool_localrc "$ai_tool" "$ai_resume"
}

# Write the profile's ai.default when ~/.localrc has no AI_TOOL yet. With
# "picker", fall back to the interactive picker when the profile has none.
install_ai_tool_default() {
    local mode="${1:-}" default
    if [[ -f "$HOME/.localrc" ]] && grep -qE '^export AI_TOOL=' "$HOME/.localrc" 2>/dev/null; then
        return 0
    fi

    default="$(profile_ai_default)"
    if [[ -n "$default" ]]; then
        if ai_is_harness "$default" && profile_lists_item "$default"; then
            ai_harness_installed "$default" || _warn "$default is the profile default but is not installed yet"
            install_ai_tool "$default"
            return
        fi
        _warn "Profile ai.default '$default' is not one of its harness items — ignoring"
    fi

    if [[ "$mode" == picker ]]; then
        install_ai_tool
    fi
}

install_dot_cli() {
    local dot_script="$DOTFILES_DIR/dot.sh"

    if [[ ! -f "$dot_script" ]]; then
        _warn "dot.sh not found in repository"
        return
    fi

    mkdir -p "$HOME/.local/bin"
    if ensure_link "$dot_script" "$HOME/.local/bin/dot"; then
        _success "Linked dot CLI to ${_DIM}~/.local/bin/dot${_RESET}"
    fi
    link_dot_bins
}

# Agents, just recipes and hooks run shells that never load functions.d/, so
# tools they call by name live in bin/ and are linked onto PATH.
link_dot_bins() {
    local name
    mkdir -p "$HOME/.local/bin"
    for name in wto; do
        [[ -x "$DOTFILES_DIR/bin/$name" ]] || continue
        ensure_link "$DOTFILES_DIR/bin/$name" "$HOME/.local/bin/$name" || true
    done
}

# ─── Core extras ──────────────────────────────────────────────────────────────

# Get the human-readable label for a core extra.
get_core_extra_label() {
    case "$1" in
        git-submodules)    echo "git-submodules — Initialize .ssh and tpm submodules" ;;
        git-config)        echo "git-config — Symlink .gitconfig and set name/email/signing" ;;
        ssh-config)        echo "ssh-config — Generate ~/.ssh/config (1Password SSH agent)" ;;
        zsh-config)        echo "zsh-config — Oh My Zsh + Powerlevel10k + plugins + .zshrc" ;;
        ai-tool)           echo "ai-tool — Default AI CLI from the profile (or pick one)" ;;
        omarchy-themes)    echo "omarchy-themes — Choose Omarchy theme submodules to install" ;;
        default-terminal)  echo "default-terminal — Set Alacritty as the Omarchy default terminal" ;;
        *)                 echo "$1" ;;
    esac
}

# Dispatch to the installer for a named core extra.
install_core_extra() {
    case "$1" in
        git-submodules)    install_git_submodules ;;
        git-config)        install_git_config ;;
        ssh-config)        install_ssh_config ;;
        zsh-config)        install_zsh_config ;;
        ai-tool)           install_ai_tool_default picker ;;
        omarchy-themes)    install_themes ;;
        default-terminal)  install_default_terminal ;;
        *)                 _warn "Unknown core extra: $1" ;;
    esac
}

# All core extras the installer knows about. Profiles pick a subset via the
# `core_extras:` field; manual mode shows the picker below.
list_all_core_extras() {
    echo "git-submodules"
    echo "git-config"
    echo "ssh-config"
    echo "zsh-config"
    echo "ai-tool"
    echo "omarchy-themes"
    echo "default-terminal"
}

# Manual-mode core extras picker — pre-selects host-compatible ones.
run_core_extras_picker() {
    local extras=() labels=() preselect_labels=()
    local item
    while IFS= read -r item; do
        local label
        label="$(get_core_extra_label "$item")"
        extras+=("$item")
        labels+=("$label")
        # Pre-select host-compatible items only
        case "$item" in
            zsh-config)
                [[ "$OSTYPE" == darwin* ]] && preselect_labels+=("$label")
                ;;
            omarchy-themes|default-terminal)
                host_has omarchy && preselect_labels+=("$label")
                ;;
            *)
                preselect_labels+=("$label")
                ;;
        esac
    done < <(list_all_core_extras)

    [[ ${#extras[@]} -eq 0 ]] && return 0

    if ! command -v gum &>/dev/null; then
        echo
        _info "gum not available — skipping core extras picker"
        return 0
    fi

    echo
    _info "Select core extras to set up (space to toggle, enter to confirm):"
    _info "${_DIM}Host-appropriate defaults pre-selected — adjust to taste.${_RESET}"
    echo

    local preselected
    preselected="$(IFS=,; echo "${preselect_labels[*]}")"

    local chosen
    chosen="$(printf '%s\n' "${labels[@]}" | gum choose --no-limit --height=10 --selected="$preselected")" || true

    [[ -z "$chosen" ]] && { _info "No core extras selected — skipping"; return 0; }

    local selected=()
    while IFS= read -r label; do
        selected+=("${label%% —*}")
    done <<< "$chosen"

    echo
    for item in "${selected[@]}"; do
        echo
        _info "${item}..."
        install_core_extra "$item" || _warn "${item} failed — continuing"
    done
}

# ─── Profiles ─────────────────────────────────────────────────────────────────

# List profile basenames (without .yaml). Skips files starting with _ or .
list_profiles() {
    local f base
    if [[ ! -d "$DOTFILES_DIR/profiles" ]]; then
        return 0
    fi
    for f in "$DOTFILES_DIR/profiles"/*.yaml; do
        [[ -e "$f" ]] || continue
        base="$(basename "$f" .yaml)"
        [[ "$base" == _* || "$base" == .* ]] && continue
        echo "$base"
    done | sort
}

# Check whether all of a profile's `requires:` predicates pass on this host.
profile_is_compatible() {
    local requires desc
    IFS=$'\x1f' read -r requires desc _ < <(profile_meta "$1") || return 1
    requires_met "$requires"
}

# Show the profile + "Manual selection" picker. Prints the chosen profile name
# (or "manual") to stdout. Returns nonzero if the user cancels.
#
# IMPORTANT: stdout is the data channel (captured by $(select_profile)). All
# user-facing output below is redirected to stderr so it doesn't pollute the
# return value.
select_profile() {
    ensure_yq >&2 || return 1
    ensure_gum >&2 || return 1

    local compat=() labels=() p requires desc
    while IFS= read -r p; do
        IFS=$'\x1f' read -r requires desc _ < <(profile_meta "$p") || continue
        if requires_met "$requires"; then
            compat+=("$p")
            if [[ -n "$desc" ]]; then
                labels+=("$p — $desc")
            else
                labels+=("$p")
            fi
        fi
    done < <(list_profiles)

    labels+=("Manual selection — pick items individually")

    {
        echo
        printf '%b\n' "${_BOLD}What do you want to install?${_RESET}"
        if [[ ${#compat[@]} -eq 0 ]]; then
            _info "${_DIM}No compatible profiles for this host — Manual selection only.${_RESET}"
        else
            _info "${_DIM}Showing profiles compatible with this host + manual selection.${_RESET}"
        fi
        echo
    } >&2

    local chosen
    chosen="$(printf '%s\n' "${labels[@]}" | gum choose --height=10)" || return 1
    [[ -z "$chosen" ]] && return 1

    if [[ "$chosen" == "Manual selection"* ]]; then
        echo "manual"
    else
        echo "${chosen%% —*}"
    fi
}

# Install everything declared by a profile: core_extras, items, post_install hooks.
# Writes .active-profile on success.
install_from_profile() {
    local name="$1"
    local file="$DOTFILES_DIR/profiles/$name.yaml"
    [[ -f "$file" ]] || { _error "Profile not found: $name"; return 1; }

    # .commonrc exports the previous profile into every shell, and
    # .active-profile is written last, so pin the one being installed.
    local pinned=""
    if [[ -f "$HOME/.localrc" ]]; then
        pinned="$(sed -nE 's/^export DOTFILES_PROFILE="?([^"]*)"?$/\1/p' "$HOME/.localrc" | tail -n 1)"
    fi
    if [[ -n "$pinned" && "$pinned" != "$name" ]]; then
        _error "DOTFILES_PROFILE=$pinned is pinned in ~/.localrc — change it there before switching to $name"
        return 1
    fi
    local -x DOTFILES_PROFILE="$name" DOTFILES_PROFILE_FROM_STATE=""
    _profile_json_load

    if ! profile_is_compatible "$name"; then
        _error "Profile '$name' requirements not met on this host"
        return 1
    fi

    _info "Installing profile: ${_BOLD}$name${_RESET}"

    # Core extras from profile
    local extras=() e
    while IFS= read -r e; do
        extras+=("$e")
    done < <(profile_list extras)

    if [[ ${#extras[@]} -gt 0 ]]; then
        echo
        _info "Profile core extras: ${extras[*]}"
        for extra in "${extras[@]}"; do
            echo
            _info "${extra}..."
            install_core_extra "$extra" || _warn "${extra} failed — continuing"
        done
    fi

    # Items from profile
    local items=() i
    while IFS= read -r i; do
        items+=("$i")
    done < <(profile_list items)

    local rc=0
    if [[ ${#items[@]} -gt 0 ]]; then
        echo
        _info "Installing ${#items[@]} items..."
        install_items "${items[@]}" || rc=1
    fi

    # Recorded even when an item failed, so dot update keeps reconciling it.
    echo "$name" > "$PROFILE_STATE_FILE"
    _success "Profile '$name' active — recorded in ${_DIM}.active-profile${_RESET}"
    return "$rc"
}

# Manual-mode installer: core extras picker + item picker (no profile state).
install_manual() {
    ensure_gum || return 1
    ensure_jq || return 1
    data_load_manifest || return 1

    run_core_extras_picker

    # Item picker — show only items whose requires are met on this host.
    local items=() labels=() item requires label
    while IFS=$'\x1f' read -r item requires label _; do
        if ai_is_harness "$item" && ! ai_harness_allowed "$item"; then
            continue
        fi
        if requires_met "$requires"; then
            items+=("$item")
            labels+=("$label")
        fi
    done < <(manifest_label_rows)

    [[ ${#items[@]} -eq 0 ]] && return 0

    echo
    _info "Select items to install (space to toggle, enter to confirm):"
    _info "${_DIM}Items marked '(+ config)' install the binary and link the dotfiles config.${_RESET}"
    echo

    local chosen
    chosen="$(printf '%s\n' "${labels[@]}" | gum choose --no-limit --height=25)" || true
    [[ -z "$chosen" ]] && return 0

    local selected=()
    while IFS= read -r label; do
        selected+=("${label%% —*}")
    done <<< "$chosen"

    echo
    install_items "${selected[@]}"
}
